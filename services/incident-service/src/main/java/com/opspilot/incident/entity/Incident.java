package com.opspilot.incident.entity;

import com.opspilot.incident.enums.IncidentStatus;
import com.opspilot.incident.enums.Severity;
import jakarta.persistence.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Incident entity — the core domain object of OpsPilot.
 * 
 * This class maps to the "incidents" table in PostgreSQL.
 * Each instance represents one production incident.
 * 
 * KEY JPA ANNOTATIONS:
 * @Entity       — tells JPA "this class = a database table"
 * @Table        — specifies the table name (default would be "Incident", we want "incidents")
 * @Id           — marks the primary key field
 * @GeneratedValue — auto-generates the primary key (UUID strategy = universally unique)
 * @Column       — customizes column behavior (nullable, unique, length, etc.)
 * @Enumerated(EnumType.STRING) — stores enum as "SEV2" not as number 1
 *                                ALWAYS use STRING, never ORDINAL (ordinal breaks if you reorder enums)
 * @CreationTimestamp — Hibernate auto-sets this when the row is first inserted
 * @UpdateTimestamp   — Hibernate auto-updates this on every save
 * 
 * WHY UUID instead of auto-increment?
 * In microservices, different services might create IDs independently.
 * UUID avoids ID conflicts across services. Also, auto-increment IDs leak information 
 * (attacker can guess INC-1043 exists after seeing INC-1042).
 */
@Entity
@Table(name = "incidents")
public class Incident {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /**
     * Human-readable incident number like "INC-1042".
     * Generated by the service, not the database.
     * Unique constraint prevents duplicates.
     */
    @Column(nullable = false, unique = true)
    private String incidentNumber;

    @Column(nullable = false)
    private String title;

    @Column(length = 2000)
    private String description;

    /** Which service is affected (e.g., "checkout-service") */
    @Column(nullable = false)
    private String serviceName;

    /** Which environment (e.g., "production", "staging") */
    @Column(nullable = false)
    private String environment;

    /**
     * @Enumerated(EnumType.STRING) is CRITICAL.
     * Without STRING, JPA stores the ordinal position (0, 1, 2, 3).
     * If you later add a new enum value between existing ones, all stored data breaks.
     * STRING stores "SEV2" as text — safe to reorder or add new values.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private Severity severity;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private IncidentStatus status;

    /** When the anomaly was first detected */
    private LocalDateTime detectedAt;

    /** When an operator acknowledged the incident */
    private LocalDateTime acknowledgedAt;

    /** When the incident was resolved */
    private LocalDateTime resolvedAt;

    /** What triggered this incident (e.g., "HIGH_ERROR_RATE_RULE", "MANUAL") */
    private String source;

    /**
     * Correlation ID for distributed tracing.
     * The same correlationId follows an incident across all services:
     * Detection → Incident → RCA → Remediation
     * This lets you trace the entire lifecycle in logs.
     */
    private String correlationId;

    @CreationTimestamp
    @Column(updatable = false)
    private LocalDateTime createdAt;

    @UpdateTimestamp
    private LocalDateTime updatedAt;

    // ====== Constructors ======

    /** JPA requires a no-args constructor */
    public Incident() {
    }

    // ====== Getters and Setters ======
    // In production, many teams use Lombok's @Getter/@Setter to avoid boilerplate.
    // We write them manually so you understand what's happening.

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public String getIncidentNumber() {
        return incidentNumber;
    }

    public void setIncidentNumber(String incidentNumber) {
        this.incidentNumber = incidentNumber;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getServiceName() {
        return serviceName;
    }

    public void setServiceName(String serviceName) {
        this.serviceName = serviceName;
    }

    public String getEnvironment() {
        return environment;
    }

    public void setEnvironment(String environment) {
        this.environment = environment;
    }

    public Severity getSeverity() {
        return severity;
    }

    public void setSeverity(Severity severity) {
        this.severity = severity;
    }

    public IncidentStatus getStatus() {
        return status;
    }

    public void setStatus(IncidentStatus status) {
        this.status = status;
    }

    public LocalDateTime getDetectedAt() {
        return detectedAt;
    }

    public void setDetectedAt(LocalDateTime detectedAt) {
        this.detectedAt = detectedAt;
    }

    public LocalDateTime getAcknowledgedAt() {
        return acknowledgedAt;
    }

    public void setAcknowledgedAt(LocalDateTime acknowledgedAt) {
        this.acknowledgedAt = acknowledgedAt;
    }

    public LocalDateTime getResolvedAt() {
        return resolvedAt;
    }

    public void setResolvedAt(LocalDateTime resolvedAt) {
        this.resolvedAt = resolvedAt;
    }

    public String getSource() {
        return source;
    }

    public void setSource(String source) {
        this.source = source;
    }

    public String getCorrelationId() {
        return correlationId;
    }

    public void setCorrelationId(String correlationId) {
        this.correlationId = correlationId;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }
}
